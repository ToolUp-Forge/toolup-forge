            "// Copyright (c) Andrew J. Willshire / ToolUp Analytics Ltd (UK)"
            "//"
            "// <auto-generated>"
            "//   Phase 69k — emitted by ToolUp.Remoting.Generator from the SAME"
            "//   record/union metadata `Write.writeRecord` and `Write.writeUnion`"
            "//   enumerate, so field positions and union tags are the writer's own"
            "//   ordering rather than a second derivation of it."
            "//"
            "//   DO NOT EDIT. Re-run the generator; a contract test in"
            "//   ToolUp.Platform.Tests holds this file to what the generator emits."
            "// </auto-generated>"
            ""
            sprintf "namespace %s" options.Namespace
            ""
            "open System"
            // Phase 804 — the algebra's home, opened explicitly. The default
            // namespace IS `ToolUp.Remoting`, where `Decode`, `Decoder` and
            // `RemotingDecoders` resolve unqualified; a consumer emitting into
            // its own namespace (samples/HelloWorld-AOT was the first) found
            // none of them without this line.
            "open ToolUp.Remoting"
        ]
        @ (options.Opens |> List.map (sprintf "open %s"))
        @ [
            ""
            "/// Generated algebra decoders: one per wire type the covered API records"
            "/// carry, registered by `registerAll` (or, verified against the reflection"
            "/// reader first, by `registerAllVerified`). Emitted by ToolUp.Remoting.Generator;"
            "/// do not edit."
            "[<RequireQualifiedAccess>]"
            sprintf "module %s =" options.ModuleName
            ""
        ]

    /// A record decoder: an applicative chain over the construction lambda.
    let private recordBody (keyword: string) (binding: string) (typeSpelling: string) (fields: FieldPlan list) =
        let parameters =
            fields
            |> List.map (fun f -> Plan.parameterName f.FieldName)
            |> String.concat " "

        // Phase 804 — the construction is ANNOTATED with the record's own
        // spelling. A type declared inside a module (`WireCorpus.Address`)
        // has labels that are not in scope unless that module is opened,
        // and the lambda handed to `Decode.succeed` is checked before the
        // binding's annotation can reach it; an annotation on the record
        // expression itself resolves the labels type-directed. Measured
        // against the alternatives: a module-qualified first label leaves
        // the remaining labels unresolved, and a `Module.Type.Label` path is
        // an invalid field label outright. Harmless where the labels were
        // already in scope, the only case the hand-written decoders met.
        let assignments =
            fields
            |> List.map (fun f -> sprintf "            %s = %s" f.FieldName (Plan.parameterName f.FieldName))
            |> String.concat "\n"

        let applies =
            fields
            |> List.map (fun f ->
                let d =
                    if f.Decoder.Contains " " then
                        "(" + f.Decoder + ")"
                    else
                        f.Decoder

                sprintf "        |> Decode.apply (Decode.field \"%s\" %d %s)" f.FieldName f.Position d)
            |> String.concat "\n"

        [
            sprintf "    %s %s: Decoder<%s> =" keyword binding typeSpelling
            sprintf "        Decode.succeed (fun %s -> ({" parameters
            assignments
            sprintf "        }: %s))" typeSpelling
            applies
            ""
        ]

    /// A union decoder: a total tag match, with an unrecognised tag
    /// refusing rather than falling through.
    let private unionBody (keyword: string) (binding: string) (typeSpelling: string) (cases: UnionCasePlan list) =
        let arms =
            cases
            |> List.collect (fun c ->
                match c.Payload with
                | CasePayload.NoFields -> [
                    sprintf "            | %d -> Some(Decode.case0 %s.%s)" c.Tag typeSpelling c.CaseName
                  ]
                | CasePayload.OneField payload ->
                    let d =
                        if payload.Contains " " then
                            "(" + payload + ")"
                        else
                            payload

                    [
                        sprintf
                            "            | %d -> Some(Decode.payload (%s |> Decode.map %s.%s))"
                            c.Tag
                            d
                            typeSpelling
                            c.CaseName
                    ]
                | CasePayload.SeveralFields fields ->
                    // Phase 800 — `fields n` over the record-shaped pipeline
                    // the case's inner array is: `succeed` the case
                    // constructor, one `field` per declared field, in order.
                    let parameters =
                        fields
                        |> List.map (fun f -> Plan.parameterName f.FieldName)
                        |> String.concat " "

                    let arguments =
                        fields
                        |> List.map (fun f -> Plan.parameterName f.FieldName)
                        |> String.concat ", "

                    let applies =
                        fields
                        |> List.map (fun f ->
                            let d =
                                if f.Decoder.Contains " " then
                                    "(" + f.Decoder + ")"
                                else
                                    f.Decoder

                            sprintf
                                "                         |> Decode.apply (Decode.field \"%s\" %d %s)"
                                f.FieldName
                                f.Position
                                d)

                    [
                        sprintf "            | %d ->" c.Tag
                        "                Some("
                        "                    Decode.fields"
                        sprintf "                        %d" (List.length fields)
                        sprintf
                            "                        (Decode.succeed (fun %s -> %s.%s(%s))"
                            parameters
                            typeSpelling
                            c.CaseName
                            arguments
                    ]
                    @ (applies
                       |> List.mapi (fun i line -> if i = List.length applies - 1 then line + ")" else line))
                    @ [ "                )" ])

        [
            sprintf "    %s %s: Decoder<%s> =" keyword binding typeSpelling
            sprintf "        Decode.union \"%s\" (function" typeSpelling
        ]
        @ arms
        @ [ "            | _ -> None)"; "" ]

    let private bindingBody (keyword: string) =
        function
        | RecordDecoder(b, t, fields) -> recordBody keyword b t fields
        | UnionDecoder(b, t, cases) -> unionBody keyword b t cases

    /// Phase 816 — a binding of a `let rec` group, eta-expanded.
    ///
    /// The body a plain binding evaluates at initialisation is wrapped in
    /// `fun value -> (…) value`, so a recursive reference inside it is read
    /// on the first DECODE rather than while the group is being built.
    /// That is what keeps a recursive plan an ordinary value: without it
    /// F# would either reject the group or guard every back-edge with a
    /// runtime initialisation check (warning FS0040), and the emitted code
    /// would carry a hazard the algebra has no name for. Applied to every
    /// member of a recursive group and to nothing else; the cost is one
    /// closure allocation per member at module load.
    let private etaExpand (lines: string list) =
        // A body line may carry several source lines joined by `\n` (the
        // record shape's assignments and applies do), so flatten first;
        // the trailing blank separator is re-appended after the wrap.
        let flat = lines |> List.collect (fun l -> l.Split '\n' |> List.ofArray)

        match flat with
        | header :: body ->
            let body = body |> List.filter (fun l -> l <> "")

            // Every body line sits at eight spaces or deeper; the wrap
            // re-homes it under the lambda at twelve, one further for the
            // continuation lines so they stay right of the opening paren.
            let wrapped =
                body
                |> List.mapi (fun i l ->
                    let content = l.Substring 8

                    let shifted =
                        if i = 0 then
                            "            (" + content
                        else
                            "             " + content

                    if i = List.length body - 1 then shifted + ")" else shifted)

            [ header; "        fun value ->" ] @ wrapped @ [ "                value"; "" ]
        | [] -> []

    /// Every key the emitted `registerAll` registers, bindings first then
    /// roots, deduplicated by `Type.FullName` and order-preserving.
    let coveredSpellings (plan: GenerationPlan) : (string * string) list =
        let bindingEntries =
            plan.Bindings |> List.map (fun b -> TypePlan.typeSpelling b, TypePlan.binding b)

        let bound = bindingEntries |> List.map fst |> Set.ofList

        let rootEntries =
            plan.Roots
            |> List.filter (fun r -> not (bound.Contains r.RootSpelling))
            |> List.map (fun r -> r.RootSpelling, r.RootDecoder)

        bindingEntries @ rootEntries

    let private coveredBlock (plan: GenerationPlan) =
        let entries =
            coveredSpellings plan
            |> List.map (fun (spelling, _) -> sprintf "        typeof<%s>.FullName" spelling)

        [
            "    /// The wire types this module covers, in registration order."
            "    let covered: string list = ["
        ]
        @ entries
        @ [ "    ]"; "" ]

    let private registerBlock (plan: GenerationPlan) =
        let registrations =
            coveredSpellings plan
            |> List.map (fun (spelling, decoder) ->
                let d =
                    if decoder.Contains " " then
                        "(" + decoder + ")"
                    else
                        decoder

                sprintf "        RemotingDecoders.register<%s> %s" spelling d)

        // Phase 801 — the differential gate, emitted beside the
        // registrations. `verifyAll` runs every decoder this module
        // registers beside the reflection reader over draws of its own
        // type, and `registerAllVerified` registers ONLY when every one
        // agrees. Phase 902 — the gate is an ARGUMENT (`DecoderGate`):
        // drawing and encoding a value need reflection and the shipped
        // writer, which live in the server tier, so the module names no
        // server symbol and compiles unguarded wherever its decoders do,
        // including a project that references Platform.Core alone.
        let verifications =
            coveredSpellings plan
            |> List.map (fun (spelling, decoder) ->
                let d =
                    if decoder.Contains " " then
                        "(" + decoder + ")"
                    else
                        decoder

                sprintf "        RemotingDecoders.verifyThrough<%s> gate draws seed %s" spelling d)

        [
            "    /// Register every decoder above. Idempotent, and explicit —"
            "    /// a static initialiser would fire at a moment nothing states,"
            "    /// so a deployment could not say whether the algebra path was live."
            "    let registerAll () : unit ="
        ]
        @ registrations
        @ [
            ""
            "    /// Phase 801 — every decoder above beside the reflection reader,"
            "    /// over `draws` draws of its own type from `seed`, through `gate`"
            "    /// (the shipped one is `RemotingDecoders.gate`, in the server tier)."
            "    /// One outcome per registration, in registration order; a refusal"
            "    /// names the type and the first diverging draw."
            "    let verifyAll (gate: DecoderGate) (draws: int) (seed: int) : Result<DecoderVerification, DecoderRefusal> list = ["
        ]
        @ verifications
        @ [
            "    ]"
            ""
            "    /// Phase 801 — `registerAll`, gated: registers every decoder above"
            "    /// only when every one verifies, and registers NOTHING otherwise, so"
            "    /// a disagreement can never leave the table half-adopted."
            "    let registerAllVerified"
            "        (gate: DecoderGate)"
            "        (draws: int)"
            "        (seed: int)"
            "        : Result<DecoderVerification list, DecoderRefusal list> ="
            "        let outcomes = verifyAll gate draws seed"
            ""
            "        let refusals ="
            "            outcomes"
            "            |> List.choose (function"
            "                | Error refusal -> Some refusal"
            "                | Ok _ -> None)"
            ""
            "        if List.isEmpty refusals then"
            "            registerAll ()"
            ""
            "            Ok("
            "                outcomes"
            "                |> List.choose (function"
            "                    | Ok verification -> Some verification"
            "                    | Error _ -> None)"
            "            )"
            "        else"
            "            Error refusals"
            ""
        ]

    let private apiRecordsBlock (options: EmitOptions) =
        if List.isEmpty options.ApiRecords then
            []
        else
            let entries =
                options.ApiRecords
                |> List.map (fun (record, wireTypes, corpusCovered) ->
                    let types =
                        wireTypes |> List.map (sprintf "typeof<%s>.FullName") |> String.concat "; "

                    sprintf "        \"%s\", [ %s ], %b" record types corpusCovered)

            [
                "    /// The API records this module covers, shaped exactly as"
                "    /// `RemotingDecoderFacet.inspect` takes them. The corpus flag is"
                "    /// DECLARED by whoever generated this file, never inferred."
                "    let coveredApiRecords: (string * string list * bool) list = ["
            ]
            @ entries
            @ [ "    ]"; "" ]

    /// Render a plan as an F# compilation unit.
    let compilationUnit (options: EmitOptions) (plan: GenerationPlan) : string =
        let sb = StringBuilder()

        let write (lines: string list) =
            lines |> List.iter (fun l -> sb.Append(l).Append('\n') |> ignore)

        write (header options)

        // Phase 816 — each recursive group (contiguous in `Bindings`, by
        // the planner's ordering) is one `let rec … and …` of eta-expanded
        // bindings; every binding outside a group is the plain `let` it
        // always was, byte for byte.
        let groupOf (name: string) =
            plan.RecursiveGroups |> List.tryFind (List.contains name)

        // Phase 801 — every binding is public surface of the module that
        // hosts it, so each carries the doc comment the tracked surface
        // asks of a public member (the doc-coverage ratchet): what it
        // decodes, and that it was read off the type rather than written.
        let docOf (binding: TypePlan) = [
            sprintf
                "    /// Generated decoder for `%s` — one combinator per field or case, read off the type's own shape."
                (TypePlan.typeSpelling binding)
        ]

        plan.Bindings
        |> List.iter (fun binding ->
            let name = TypePlan.binding binding

            match groupOf name with
            | None -> write (docOf binding @ bindingBody "let" binding)
            | Some group ->
                let keyword = if List.head group = name then "let rec" else "and"
                write (docOf binding @ etaExpand (bindingBody keyword binding)))

        write (coveredBlock plan)
        write (registerBlock plan)
        write (apiRecordsBlock options)
        sb.ToString()

    // ─── Phase 841 — the JSON argument side ──────────────────────────
    //
    // The response side's emission pattern, transposed onto Phase 799's
    // surface: named decoders in dependency order (recursive groups as
    // eta-expanded `let rec … and …`, Phase 816), then `covered`, then
    // `coveredApiRecords`, then `registerAll`, then — .NET only — the
    // Phase 840 gate as `verifyAll` / `registerAllVerified`. Two things
    // differ from the MessagePack emission and both come from the wire:
    // every registration is SCOPED to its API record (Phase 839), so the
    // entries are `(record, type)` pairs rather than types; and the gate's
    // oracle is a PARAMETER, because the converter set it compares against
    // is composed in `Platform.Server`, which the emitted module's assembly
    // cannot reference (Phase 840's `JsonDecoderOracle`).

    let private jsonHeader (options: JsonEmitOptions) =
        [
            "// SPDX-License-Identifier: Apache-2.0"
            "// Copyright (c) Andrew J. Willshire / ToolUp Analytics Ltd (UK)"
            "//"
            "// <auto-generated>"
            "//   Phase 841 — emitted by ToolUp.Remoting.Generator from the SAME"
            "//   record/union metadata the System.Text.Json converter set reads:"
            "//   record members by NAME, union cases by case NAME, one decoder per"
            "//   argument type an API record's methods take."
            "//"
            "//   DO NOT EDIT. Re-run the generator; a contract test in"
            "//   ToolUp.Platform.Tests holds this file to what the generator emits."
            "// </auto-generated>"
            ""
            sprintf "namespace %s" options.JsonNamespace
            ""
            "open System"
            "open ToolUp.Remoting"
            "open ToolUp.Remoting.Json"
        ]
        @ (options.JsonOpens |> List.map (sprintf "open %s"))
        @ [
            ""
            "/// Generated JSON algebra decoders for the ARGUMENTS the covered API"
            "/// records' methods take, each registered scoped to its own record by"
            "/// `registerAll` (or, verified against the System.Text.Json converter set"
            "/// first, by `registerAllVerified`). Emitted by ToolUp.Remoting.Generator;"
            "/// do not edit."
            "[<RequireQualifiedAccess>]"
            sprintf "module %s =" options.JsonModuleName
            ""
        ]

    let private parenthesise (expr: string) =
        if expr.Contains " " then "(" + expr + ")" else expr

    /// A JSON record decoder: the construction lambda, then one
    /// `JsonDecode.apply` per member read the plan chose.
    let private jsonRecordBody (keyword: string) (binding: string) (typeSpelling: string) (fields: FieldPlan list) =
        let parameters =
            fields
            |> List.map (fun f -> Plan.parameterName f.FieldName)
            |> String.concat " "

        let assignments =
            fields
            |> List.map (fun f -> sprintf "            %s = %s" f.FieldName (Plan.parameterName f.FieldName))
            |> String.concat "\n"

        let applies =
            fields
            |> List.map (fun f -> sprintf "        |> JsonDecode.apply (%s)" f.Decoder)
            |> String.concat "\n"

        [
            sprintf "    %s %s: JsonDecoder<%s> =" keyword binding typeSpelling
            sprintf "        JsonDecode.succeed (fun %s -> ({" parameters
            assignments
            sprintf "        }: %s))" typeSpelling
            applies
            ""
        ]

    /// A JSON union decoder: a total match on the CASE NAME, an
    /// unrecognised name refusing rather than falling through.
    let private jsonUnionBody (keyword: string) (binding: string) (typeSpelling: string) (cases: UnionCasePlan list) =
        let arms =
            cases
            |> List.collect (fun c ->
                match c.Payload with
                | CasePayload.NoFields -> [
                    sprintf "            | \"%s\" -> Some(JsonDecode.case0 %s.%s)" c.CaseName typeSpelling c.CaseName
                  ]
                | CasePayload.OneField payload -> [
                    sprintf
                        "            | \"%s\" -> Some(JsonDecode.payload (%s |> JsonDecode.map %s.%s))"
                        c.CaseName
                        (parenthesise payload)
                        typeSpelling
                        c.CaseName
                  ]
                | CasePayload.SeveralFields fields ->
                    let parameters =
                        fields
                        |> List.map (fun f -> Plan.parameterName f.FieldName)
                        |> String.concat " "

                    let arguments =
                        fields
                        |> List.map (fun f -> Plan.parameterName f.FieldName)
                        |> String.concat ", "

                    let applies =
                        fields
                        |> List.map (fun f -> sprintf "                         |> JsonDecode.apply (%s)" f.Decoder)

                    [
                        sprintf "            | \"%s\" ->" c.CaseName
                        "                Some("
                        "                    JsonDecode.fields"
                        sprintf "                        %d" (List.length fields)
                        sprintf
                            "                        (JsonDecode.succeed (fun %s -> %s.%s(%s))"
                            parameters
                            typeSpelling
                            c.CaseName
                            arguments
                    ]
                    @ (applies
                       |> List.mapi (fun i line -> if i = List.length applies - 1 then line + ")" else line))
                    @ [ "                )" ])

        [
            sprintf "    %s %s: JsonDecoder<%s> =" keyword binding typeSpelling
            sprintf "        JsonDecode.union \"%s\" (function" typeSpelling
        ]
        @ arms
        @ [ "            | _ -> None)"; "" ]

    let private jsonBindingBody (keyword: string) =
        function
        | RecordDecoder(b, t, fields) -> jsonRecordBody keyword b t fields
        | UnionDecoder(b, t, cases) -> jsonUnionBody keyword b t cases

    /// Phase 841 — every `(API record, argument type spelling, decoder
    /// expression)` the emitted `registerAll` registers, in `ArgumentRecords`
    /// order then each record's own argument order. A spelling the plan
    /// has no root for is absent: the plan refused it, by name.
    let jsonRegistrations (options: JsonEmitOptions) (plan: GenerationPlan) : (string * string * string) list =
        let decoders =
            plan.Roots |> List.map (fun r -> r.RootSpelling, r.RootDecoder) |> Map.ofList

        options.ArgumentRecords
        |> List.collect (fun (record, spellings) ->
            spellings
            |> List.choose (fun spelling ->
                decoders |> Map.tryFind spelling |> Option.map (fun d -> record, spelling, d)))

    /// Phase 841 — the API records every one of whose arguments the plan
    /// expressed, in `ArgumentRecords` order: the argument-side census. A record
    /// that takes no argument at all is in it — it has nothing for the
    /// converter set to decode — exactly as the served argument facet
    /// classifies it.
    let jsonCoveredApiRecords (options: JsonEmitOptions) (plan: GenerationPlan) : string list =
        let planned = plan.Roots |> List.map _.RootSpelling |> Set.ofList

        options.ArgumentRecords
        |> List.filter (fun (_, spellings) -> spellings |> List.forall planned.Contains)
        |> List.map fst

    let private jsonRegisterBlock (options: JsonEmitOptions) (plan: GenerationPlan) =
        let registrations = jsonRegistrations options plan

        let covered =
            registrations
            |> List.map (fun (record, spelling, _) ->
                sprintf "        Some \"%s\", typeof<%s>.FullName" record spelling)

        let records =
            jsonCoveredApiRecords options plan |> List.map (sprintf "        \"%s\"")

        let registers =
            registrations
            |> List.map (fun (record, spelling, decoder) ->
                sprintf "        JsonDecoders.registerFor<%s> \"%s\" %s" spelling record (parenthesise decoder))

        let verifications =
            registrations
            |> List.map (fun (record, spelling, decoder) ->
                sprintf
                    "            (Some \"%s\", typeof<%s>.FullName), JsonDecoders.verifyThrough<%s> gate draws seed %s"
                    record
                    spelling
                    spelling
                    (parenthesise decoder))

        [
            "    /// The `(API record, argument type)` pairs this module registers, in"
            "    /// registration order — each decoder scoped to the one record whose"
            "    /// methods take it (Phase 839), never to every record of the same type."
            "    let covered: (string option * string) list = ["
        ]
        @ covered
        @ [
            "    ]"
            ""
            "    /// The API records every one of whose arguments this module decodes"
            "    /// through the JSON algebra — the argument-side census. A record taking"
            "    /// no argument at all is included: nothing of it reaches the converter set."
            "    let coveredApiRecords: string list = ["
        ]
        @ records
        @ [
            "    ]"
            ""
            "    /// Register every decoder above, each scoped to its API record. Idempotent,"
            "    /// and explicit — a static initialiser would fire at a moment nothing"
            "    /// states, so a deployment could not say whether the algebra path was live."
            "    let registerAll () : unit ="
        ]
        @ (if List.isEmpty registers then
               [ "        ()" ]
           else
               registers)
        @ [
            ""
            "    /// Phase 840's gate over every registration above: each decoder through"
            "    /// `gate` over `draws` draws of its own type from `seed`, keyed as"
            "    /// `covered` is. The shipped gate is `JsonDecoders.gateWith"
            "    /// FableConverters.decoderOracle`, in the server tier: every draw"
            "    /// written by the server's writer AND the browser's (Phase 885)."
            "    let verifyAll"
            "        (gate: JsonDecoderGate)"
            "        (draws: int)"
            "        (seed: int)"
            "        : ((string option * string) * Result<JsonDecoderVerification, DecoderRefusal>) list ="
            "        ["
        ]
        @ verifications
        @ [
            "        ]"
            ""
            "    /// `registerAll`, gated: registers every decoder above only when every"
            "    /// one passes `gate`, and registers NOTHING otherwise, so a"
            "    /// disagreement can never leave the table half-adopted."
            "    let registerAllVerified"
            "        (gate: JsonDecoderGate)"
            "        (draws: int)"
            "        (seed: int)"
            "        : Result<JsonDecoderVerification list, DecoderRefusal list> ="
            "        let outcomes = verifyAll gate draws seed |> List.map snd"
            ""
            "        let refusals ="
            "            outcomes"
            "            |> List.choose (function"
            "                | Error refusal -> Some refusal"
            "                | Ok _ -> None)"
            ""
            "        if List.isEmpty refusals then"
            "            registerAll ()"
            ""
            "            Ok("
            "                outcomes"
            "                |> List.choose (function"
            "                    | Ok verification -> Some verification"
            "                    | Error _ -> None)"
            "            )"
            "        else"
            "            Error refusals"
            ""
        ]

    /// Phase 841 — render a JSON-wire plan (`Plan.forJsonTypes`) as the
    /// argument side's F# compilation unit. Every generated binding carries
    /// a doc comment: each is tracked public surface of the module that
    /// hosts it, and an emission without them would move the doc-coverage
    /// ratchet by one per binding (Phase 801's measured lesson).
    let jsonCompilationUnit (options: JsonEmitOptions) (plan: GenerationPlan) : string =
        let sb = StringBuilder()

        let write (lines: string list) =
            lines |> List.iter (fun l -> sb.Append(l).Append('\n') |> ignore)

        write (jsonHeader options)

        let groupOf (name: string) =
            plan.RecursiveGroups |> List.tryFind (List.contains name)

        let docOf (binding: TypePlan) = [
            sprintf
                "    /// Generated JSON decoder for `%s` — members by name, cases by case name, read off the type's own shape."
                (TypePlan.typeSpelling binding)
        ]

        plan.Bindings
        |> List.iter (fun binding ->
            let name = TypePlan.binding binding

            match groupOf name with
            | None -> write (docOf binding @ jsonBindingBody "let" binding)
            | Some group ->
                let keyword = if List.head group = name then "let rec" else "and"
                write (docOf binding @ etaExpand (jsonBindingBody keyword binding)))

        write (jsonRegisterBlock options plan)
        sb.ToString()

    // ─── Phase 853 — generated client proxies ────────────────────────
    //
    // One module per run: the argument ENCODERS (`Plan.forJsonEncoders`),
    // the response DECODERS (`Plan.forJsonResponseDecoders`), then one proxy
    // builder per API record — a record VALUE whose fields are closures over
    // the encoders, the transport (`Proxy.generatedMethod`) and the decoder —
    // then the lookup `Api.makeProxy` consults and the `registerAll` a
    // consumer's own module is mounted by. Nothing in it reflects: no
    // `createTypeInfo`, no `Convert.serialize`, no `typeof`.
    //
    // Its decoders are BUILT AT IMPORT, deliberately (Phase 909). Building
    // each on first use instead — the body inside a `lazy`, the binding
    // forcing it on the first decode — was emitted, regenerated and measured
    // under Node, interleaved A/B in fresh processes with only this module's
    // output swapped: evaluating the module ROSE from 9.3 to 10.7 ms (min of
    // 8), its import with everything it imports went 149.3 -> 147.5 ms and
    // the whole SDK shell's import 615 -> 604 ms (min of 10, both inside the
    // run-to-run spread), and the shell's production bundle grew 10.7 KB. A
    // combinator chain is a handful of closure allocations; a `Lazy` plus
    // its wrapper costs about as much as it defers, and the larger source
    // costs more to parse. Re-measure with ClientBench's generated-module
    // import lever (`generatedModuleImportMsMin`) before changing this.

    let private clientHeader (options: ClientEmitOptions) =
        [
            "// SPDX-License-Identifier: Apache-2.0"
            "// Copyright (c) Andrew J. Willshire / ToolUp Analytics Ltd (UK)"
            "//"
            "// <auto-generated>"
            "//   Phase 853 — emitted by ToolUp.Remoting.Generator from the SAME"
            "//   record/union metadata the System.Text.Json converter set reads:"
            "//   one encoder per argument type and one decoder per response type an"
            "//   API record's methods carry, and one proxy builder per record."
            "//"
            "//   DO NOT EDIT. Re-run the generator; a contract test in"
            "//   ToolUp.Platform.Tests holds this file to what the generator emits."
            "// </auto-generated>"
            ""
            sprintf "namespace %s" options.ClientNamespace
            ""
            "open System"
            "open ToolUp.Remoting"
            "open ToolUp.Remoting.Json"
            "open ToolUp.Remoting.Client"
        ]
        @ (options.ClientOpens |> List.map (sprintf "open %s"))
        @ [
            ""
            "/// Generated client proxies: each API record's methods build their request"
            "/// through generated encoders and read their response through generated"
            "/// decoders, with no reflection at construction or per call. Emitted by"
            "/// ToolUp.Remoting.Generator; do not edit."
            "[<RequireQualifiedAccess>]"
            sprintf "module %s =" options.ClientModuleName
            ""
        ]

    /// A record ENCODER: an object of the members, in declaration order,
    /// each written by its value's encoder.
    let private encoderRecordBody (keyword: string) (binding: string) (typeSpelling: string) (fields: FieldPlan list) =
        [
            sprintf "    %s %s: JsonEncoder<%s> =" keyword binding typeSpelling
            sprintf "        fun (value: %s) ->" typeSpelling
            "            JsonEncode.record ["
        ]
        @ (fields
           |> List.map (fun f ->
               sprintf "                \"%s\", %s value.%s" f.FieldName (parenthesise f.Decoder) f.FieldName))
        @ [ "            ]"; "" ]

    /// A union ENCODER: a total match writing each case by its NAME.
    let private encoderUnionBody
        (keyword: string)
        (binding: string)
        (typeSpelling: string)
        (cases: UnionCasePlan list)
        =
        let arms =
            cases
            |> List.map (fun c ->
                match c.Payload with
                | CasePayload.NoFields ->
                    sprintf "        | %s.%s -> JsonEncode.case0 \"%s\"" typeSpelling c.CaseName c.CaseName
                | CasePayload.OneField encoder ->
                    sprintf
                        "        | %s.%s field -> JsonEncode.payload \"%s\" (%s field)"
                        typeSpelling
                        c.CaseName
                        c.CaseName
                        (parenthesise encoder)
                | CasePayload.SeveralFields fields ->
                    let parameters = fields |> List.map (fun f -> Plan.parameterName f.FieldName)

                    let values =
                        List.zip fields parameters
                        |> List.map (fun (f, p) -> sprintf "%s %s" (parenthesise f.Decoder) p)
                        |> String.concat "; "

                    sprintf
                        "        | %s.%s(%s) -> JsonEncode.fields \"%s\" [ %s ]"
                        typeSpelling
                        c.CaseName
                        (String.concat ", " parameters)
                        c.CaseName
                        values)

        [
            sprintf "    %s %s: JsonEncoder<%s> =" keyword binding typeSpelling
            "        function"
        ]
        @ arms
        @ [ "" ]

    let private encoderBindingBody (keyword: string) =
        function
        | RecordDecoder(b, t, fields) -> encoderRecordBody keyword b t fields
        | UnionDecoder(b, t, cases) -> encoderUnionBody keyword b t cases

    /// Render one plan's bindings — plain `let`s, a recursive group as one
    /// eta-expanded `let rec … and …` — each under its doc line.
    let private renderBindings
        (plan: GenerationPlan)
        (doc: TypePlan -> string)
        (body: string -> TypePlan -> string list)
        : string list =
        let groupOf (name: string) =
            plan.RecursiveGroups |> List.tryFind (List.contains name)

        plan.Bindings
        |> List.collect (fun binding ->
            let name = TypePlan.binding binding

            match groupOf name with
            | None -> doc binding :: body "let" binding
            | Some group ->
                let keyword = if List.head group = name then "let rec" else "and"
                doc binding :: etaExpand (body keyword binding))

    /// The proxy builder's binding name for a record.
    let private proxyBinding (record: ClientRecordPlan) =
        Plan.camelCase record.RecordName + "Proxy"

    let private policyExpr (policy: ClientReadPolicy) =
        let quoted = policy.Invalidates |> List.map (sprintf "\"%s\"") |> String.concat "; "

        match policy.MaxAgeSeconds with
        | Some seconds when List.isEmpty policy.Invalidates ->
            sprintf "\"%s\", ReadPolicy.cacheable %d" policy.PolicyMethod seconds
        | None -> sprintf "\"%s\", ReadPolicy.invalidates [ %s ]" policy.PolicyMethod quoted
        | Some seconds ->
            sprintf
                "\"%s\", ({ MaxAgeSeconds = Some %d; Invalidates = [ %s ] }: ReadPolicy)"
                policy.PolicyMethod
                seconds
                quoted

    let private proxyBody (record: ClientRecordPlan) =
        let call (m: ClientMethodPlan) = "call" + m.MethodName

        let calls =
            record.Methods
            |> List.map (fun m ->
                sprintf
                    "        let %s = Proxy.generatedMethod<%s> api \"%s\" %s %s"
                    (call m)
                    m.ReturnSpelling
                    m.MethodName
                    (if m.SendsBody then "true" else "false")
                    (parenthesise m.ReturnDecoder))

        let registration =
            if List.isEmpty record.ReadPolicies then
                []
            else
                [ sprintf "        ReadPolicies.register \"%s\" [" record.RecordKey ]
                @ (record.ReadPolicies |> List.map (policyExpr >> sprintf "            %s"))
                @ [ "        ]"; "" ]

        let fields =
            record.Methods
            |> List.map (fun m ->
                match m.ArgumentEncoders with
                // A GET's body text is only the read-policy key's tail —
                // the one the reflective proxy uses (`[]` / `{}`).
                | [] -> sprintf "            %s = %s \"[]\"" m.MethodName (call m)
                | _ when not m.SendsBody -> sprintf "            %s = fun () -> %s \"{}\"" m.MethodName (call m)
                | encoders ->
                    let parameters = encoders |> List.mapi (fun i _ -> sprintf "a%d" i)

                    let values =
                        List.zip encoders parameters
                        |> List.map (fun (e, p) -> sprintf "%s %s" (parenthesise e) p)
                        |> String.concat "; "

                    sprintf
                        "            %s = fun %s -> %s (JsonEncode.arguments [ %s ])"
                        m.MethodName
                        (String.concat " " parameters)
                        (call m)
                        values)

        [
            sprintf
                "    /// Generated client proxy for `%s` — %d method(s), each a closure over its"
                record.RecordSpelling
                (List.length record.Methods)
            "    /// generated encoders, the transport and its generated response decoder."
            sprintf "    let %s (options: RemoteBuilderOptions) : %s =" (proxyBinding record) record.RecordSpelling
        ]
        @ registration
        @ [
            sprintf "        let api = Proxy.generatedApi \"%s\" \"%s\" options" record.RecordKey record.RecordName
        ]
        @ calls
        @ [ ""; "        {" ]
        @ fields
        @ [ "        }"; "" ]

    let private clientRegistryBlock (plan: ClientPlan) =
        let covered =
            plan.Records |> List.map (fun r -> sprintf "        \"%s\"" r.RecordKey)

        let arms =
            plan.Records
            |> List.map (fun r -> sprintf "        | \"%s\" -> Some(box (%s options))" r.RecordKey (proxyBinding r))

        let registers =
            plan.Records
            |> List.map (fun r ->
                sprintf
                    "        GeneratedProxies.register \"%s\" (fun options -> box (%s options))"
                    r.RecordKey
                    (proxyBinding r))

        [
            "    /// The API records this module builds a generated proxy for, by the key"
            "    /// `Api.makeProxy` looks a record up under."
            "    let coveredApiRecords: string list = ["
        ]
        @ covered
        @ [
            "    ]"
            ""
            "    /// The generated proxy for the record `apiKey` names, built over"
            "    /// `options`; `None` for a record this module does not cover."
            "    let tryBuild (apiKey: string) (options: RemoteBuilderOptions) : obj option ="
            "        match apiKey with"
        ]
        @ arms
        @ [
            "        | _ -> None"
            ""
            "    /// Register every proxy builder above with `GeneratedProxies`, where"
            "    /// `Api.makeProxy` finds it. Idempotent; call it at composition. A proxy"
            "    /// built before it runs resolves on its first call instead."
            "    let registerAll () : unit ="
        ]
        @ (if List.isEmpty registers then
               [ "        ()" ]
           else
               registers)
        @ [ "" ]

    /// Phase 853 — render a client plan (`Plan.forClientProxies`) as the
    /// generated client-proxy compilation unit. Every binding carries a
    /// doc comment, for 841.D's reason.
    let clientCompilationUnit (options: ClientEmitOptions) (plan: ClientPlan) : string =
        let sb = StringBuilder()

        let write (lines: string list) =
            lines |> List.iter (fun l -> sb.Append(l).Append('\n') |> ignore)

        write (clientHeader options)

        write (
            renderBindings
                plan.Encoders
                (fun b ->
                    sprintf
                        "    /// Generated JSON encoder for `%s` — members by name, cases by case name, as the writer emits them."
                        (TypePlan.typeSpelling b))
                encoderBindingBody
        )

        write (
            renderBindings
                plan.Decoders
                (fun b ->
                    sprintf
                        "    /// Generated JSON decoder for `%s` — members by name, cases by case name, read off the type's own shape."
                        (TypePlan.typeSpelling b))
                jsonBindingBody
        )

        plan.Records |> List.iter (proxyBody >> write)
        write (clientRegistryBlock plan)
        sb.ToString()

    /// Phase 853 — the records a client plan did NOT generate, rendered for
    /// a human (the CLI prints it), with each plan's refusals beneath.
    let clientSkipReport (plan: ClientPlan) : string =
        let skipped =
            if List.isEmpty plan.Skipped then
                "every requested API record has a generated proxy"
            else
                plan.Skipped
                |> List.map (fun r -> sprintf "  %s\n    %s" r.RefusedType r.Why)
                |> String.concat "\n"

        skipped

    /// The refusals, rendered for a human. Printed by the CLI rather than
    /// emitted into the file: a refused type keeps the reflection path, and
    /// a comment in a generated file is not where an operator looks.
    let refusalReport (plan: GenerationPlan) : string =
        if List.isEmpty plan.Refusals then
            "no refusals — every requested wire type is expressible in the closed algebra"
        else
            plan.Refusals
            |> List.map (fun r -> sprintf "  %s\n    %s" r.RefusedType r.Why)
            |> String.concat "\n"
            |> sprintf "%d wire type(s) kept the reflection path:\n%s" (List.length plan.Refusals)