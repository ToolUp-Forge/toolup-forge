/// Stop-word lists for the languages this companion serves.
///
/// Stop-word removal is the *other* half of the recall story, and it is the
/// half that works without a per-language stemmer: BM25 already down-weights
/// terms that appear in most documents via IDF, so the win here is not ranking
/// but cost and precision — a query like "what is the policy for expenses"
/// stops fanning out over the posting lists of `what` / `is` / `the` / `for`,
/// which in a small corpus are long enough to dominate the candidate pool.
///
/// The lists are deliberately conservative. An aggressive list removes terms
/// that carry meaning in a phrase query (`to be or not to be` becomes empty),
/// which is why the analyzer refuses to return an empty term list purely
/// because every term was a stop word — see `SnowballAnalyzer`.
///
/// Words are stored lower-cased and diacritic-bearing forms are listed as they
/// are written; the analyzer applies stop-word removal BEFORE folding so a
/// folding deployment and a non-folding one drop the same words.
module ToolUp.SparseIndices.Snowball.StopWords

/// The languages this companion carries lists (and, for English, a stemmer)
/// for. `Language` is part of the analyzer id, so changing it invalidates a
/// persisted index snapshot rather than silently mixing vocabularies.
type Language =
    | English
    | French
    | German
    | Spanish
    | Italian
    | Dutch
    | Portuguese

/// Stable, lower-case tag used in the analyzer id and in configuration.
let tag (language: Language) =
    match language with
    | English -> "en"
    | French -> "fr"
    | German -> "de"
    | Spanish -> "es"
    | Italian -> "it"
    | Dutch -> "nl"
    | Portuguese -> "pt"

/// Parse a language tag; `None` for anything this companion does not serve.
/// Case-insensitive so configuration can be written either way.
let tryParse (value: string) =
    match (if isNull value then "" else value.Trim().ToLowerInvariant()) with
    | "en"
    | "english" -> Some English
    | "fr"
    | "french" -> Some French
    | "de"
    | "german" -> Some German
    | "es"
    | "spanish" -> Some Spanish
    | "it"
    | "italian" -> Some Italian
    | "nl"
    | "dutch" -> Some Dutch
    | "pt"
    | "portuguese" -> Some Portuguese
    | _ -> None

