/// The stop-word set for a language. Built once per language and shared —
/// `Set<string>` lookup is O(log n) and these lists are static.
let forLanguage (language: Language) : Set<string> =
    match language with
    | English -> Set.ofList english
    | French -> Set.ofList french
    | German -> Set.ofList german
    | Spanish -> Set.ofList spanish
    | Italian -> Set.ofList italian
    | Dutch -> Set.ofList dutch
    | Portuguese -> Set.ofList portuguese