// ─── Central config-key registry ─────────────────────────────────────
//
// A large surface of composition-root behaviour is set by environment
// variables (the `*FromEnv` readers: blob storage, secret store, auth
// provider, logging, health checks, …). This module is the single source
// of truth for *what those keys are*: each `ConfigKey` in `keys` states its
// name, its kind with a typed default (and, by kind, its bounds or its
// choices and the direction a malformed value fails in), a one-line
// description, whether the resolved value is a secret, and whether it
// enters the boot seal. From this one list:
//
//   * `ServerConfig.fromEnv` takes each key's parser, default and bounds;
//   * `ReferenceDoc.render` projects `docs/reference/config-reference.md`,
//     `ConfigSchema.render` the manifest schema and `DeploymentDoc.render`
//     the directions and seal-coverage region of `DEPLOYMENT.md` (all
//     regenerated by the `GenerateConfigReference` Build target, never
//     hand-maintained — the golden-file tests fail if one drifts);
//   * `ConfigKeySeal.project` renders what the boot seal records;
//   * `--print-config` (see `StartupModes`) reads each key's effective
//     value and prints it, redacting the `IsSecret` ones;
//   * the coverage tests assert every key the readers consult carries an
//     entry here.
//
// The module is deliberately dependency-free (System / FSharp.Core only)
// so it can sit early in the compile order and the `*FromEnv` readers can
// reference `Names.*` instead of duplicating string literals — a renamed
// env var then fails to compile rather than silently drifting from the
// reference doc.

/// The value-kind a config key resolves to. Drives the "Type" column in
/// the generated reference and how `--print-config` labels the value.
type ConfigKeyType =
    | StringKey
    | BoolKey
    | IntKey
    /// A closed set of accepted string values (case-insensitive at the
    /// reader). The list is the recognised set; an unset var falls back
    /// to the descriptor's `Default`.
    | EnumKey of choices: string list

/// Phase 719 — the token set the enabled/disabled reader family accepts,
/// declared once because the readers accept it once.
///
/// `ServerConfig.fromEnv`'s `enabledDisabledTokens` maps six spellings
/// onto the two `No* | Enabled*` cases, and every binary toggle in the
/// registry goes through it. Each of those descriptors used to declare
/// two of the six, so four working spellings were flagged invalid by the
/// generated schema on twenty-three keys at once — a projection telling
/// an operator that the value their deployment is running on is not
/// allowed.
///
/// One shared list rather than twenty-three copies: the readers share a
/// helper, so the declaration that describes them shares a value. A
/// seventh token added to the reader is then a one-line change here, and
/// cannot be added to twenty-two descriptors and forgotten on the
/// twenty-third. The canonical spelling leads, and the doc's "enum:"
/// cell renders in this order.
///
/// **Not every enabled/disabled-shaped key belongs here.**
/// `TOOLUP_AUTH_COOKIE_ISSUANCE` and
/// `TOOLUP_REQUIRE_DIRECTORY_PROOF_FOR_DIRECT_ADD` read their own token
/// lists (numeric and boolean spellings respectively), so they declare
/// their own — sharing this one would be a declaration that does not
/// describe its reader, which is the defect, not the fix.
let enabledDisabledChoices = [ "enabled"; "on"; "yes"; "disabled"; "no"; "off" ]

/// Which way a malformed value fails — the direction rule, carried as data.
///
/// Ask what an unrecognised value would leave. If a typo could leave a
/// protection or a behaviour the operator asked for switched OFF
/// (`TOOLUP_REQUIRE_HTTPS=Ture`, `TOOLUP_SECURITY_HARDENING=stric`), the key
/// is `Protective` and its reader refuses the boot, naming the key, the
/// value as written and what it accepts. If the safe failure is to keep the
/// default (an `Accept*` escape hatch read as `false` leaves its refusal
/// standing), the key is `Permissive` and its reader warns or reads the
/// value as off.
///
/// It records what the key's reader DOES. A reader that resolves through
/// the registry (`ServerConfig.fromEnv`) chooses its parser from it, so for
/// those keys the two cannot disagree.
[<RequireQualifiedAccess>]
type Direction =
    /// A malformed value refuses the boot.
    | Protective
    /// A malformed value keeps the safe reading: a warning and the default,
    /// or `false` for a boolean.
    | Permissive

/// Whether, and how, a key's resolved value enters the boot seal.
[<RequireQualifiedAccess>]
type SealPosture =
    /// The resolved value (or the typed default, when unset) is sealed.
    | SealValue
    /// Only whether the key is set is sealed. Every secret takes this: the
    /// seal is persisted beside the deploy record, so a sealed value would
    /// write the credential down, while presence alone still reports a
    /// change of posture (a master key provisioned or withdrawn).
    | SealPresence
    /// Not sealed, and why. A change to the key is not composition drift.
    | Unsealed of reason: string

/// How the reader behind an `IntKey` parses its numeric value.
///
/// Two cases because the registry has two, not because a taxonomy was
/// wanted: every int key but one is `Int32`/`Int64.TryParse`, and
/// `TOOLUP_STORE_EVICTION_MINUTES` is `Double.TryParse`.
type IntKeyNumericForm =
    /// `Int32.TryParse` / `Int64.TryParse` — digits, optionally signed.
    | IntegerOnly
    /// `Double.TryParse` — a fractional value is honoured by the reader.
    | IntegerOrDecimal

/// The value contract of an integer-valued key: the range it accepts, the
/// non-numeric tokens its reader treats as "unset", and the numeric form it
/// parses.
///
/// Bounds are INCLUSIVE, and stated in the key's own unit (bytes for a
/// byte cap) so a refusal can quote the number the operator typed against
/// the number the key accepts.
type IntBounds = {
    /// Inclusive lower bound, when the key declares one.
    Min: int64 option
    /// Inclusive upper bound, when the key declares one.
    Max: int64 option
    /// Raw values accepted verbatim, bypassing both the numeric format and
    /// the range — the reader's own "unset" / "disabled" tokens. Compared
    /// case-insensitively, as the readers compare them.
    AcceptedTokens: string list
    Form: IntKeyNumericForm
}

[<RequireQualifiedAccess>]
module IntBounds =

    /// No range, no tokens, integer format.
    let unconstrained: IntBounds = {
        Min = None
        Max = None
        AcceptedTokens = []
        Form = IntegerOnly
    }

/// What a key holds, with its default TYPED by the kind — a closed set.
///
/// The default is the value the key's reader binds when the key is unset.
/// `None` means no value is bound (the feature is off, or the reader derives
/// its behaviour from something else, as the description says).
[<RequireQualifiedAccess>]
type ConfigKeyKind =
    /// A boolean. `1` / `true` / `yes` / `on` read as on; what anything else
    /// does is the `Direction`.
    | BoolKey of direction: Direction * defaultValue: bool option
    /// An integer (or, under `IntegerOrDecimal`, a decimal) within its
    /// bounds.
    | IntKey of bounds: IntBounds * defaultValue: int64 option
    /// One of a closed set of tokens, compared case-insensitively. The
    /// default, when there is one, is one of the choices.
    | EnumKey of choices: string list * direction: Direction * defaultValue: string option
    /// Free text.
    | StringKey of defaultValue: string option

/// One environment-variable-backed config key, untyped: the projection of a
/// `ConfigKey` (below) that the readers predating the typed kind consume.
/// Never authored directly — `all` derives every one from `keys`.
type ConfigKeyDescriptor = {
    /// The environment variable name, e.g. `"TOOLUP_AUTH_MODE"`.
    EnvVar: string
    /// What the value means / how it is used (one line).
    Description: string
    Type: ConfigKeyType
    /// The effective value when the var is unset, rendered verbatim into
    /// the doc's "Default" column. `None` when there is no default — the
    /// feature is simply off / unset until the operator sets the var.
    Default: string option
    /// `true` when the resolved value is sensitive (master keys, admin
    /// tokens, connection strings carrying credentials). `--print-config`
    /// redacts these; the reference doc flags them so an operator knows
    /// not to commit the value.
    IsSecret: bool
    /// Grouping bucket for the reference doc's section headings. Stable,
    /// human-facing strings (e.g. `"Auth"`, `"Storage & secrets"`).
    Category: string
}

/// One environment-variable-backed config key, stated once: its name, what
/// it holds (kind, typed default, bounds, direction) and whether it enters
/// the boot seal.
///
/// `keys` below is the registry. `ConfigKeyDescriptor` (and `all`) is its
/// untyped projection, kept for the readers that predate the kind; the
/// parser `ServerConfig.fromEnv` picks for a key, the default it binds and
/// the bounds it enforces are read from here, so none of them can disagree
/// with the generated reference.
///
/// `Category` is also the key's CONCERN: the grouping the reference doc
/// renders as sections is the one a nested `ServerConfig` splits by.
type ConfigKey = {
    /// The environment variable name, e.g. `"TOOLUP_AUTH_MODE"`.
    EnvVar: string
    /// What the value means / how it is used, including what an unset key
    /// means when the kind has no typed default.
    Description: string
    Kind: ConfigKeyKind
    /// `true` when the resolved value is sensitive. `--print-config`
    /// redacts these, the manifest refuses them, and the seal records only
    /// their presence.
    IsSecret: bool
    /// Grouping bucket for the reference doc's section headings, and the
    /// key's concern.
    Category: string
    /// Whether, and how, the key enters the boot seal.
    Seal: SealPosture
}

/// The spellings every boolean reader that resolves through the registry
/// accepts as on, compared case-insensitively after trimming.
let trueTokens: Set<string> = set [ "1"; "true"; "yes"; "on" ]

/// The spellings it accepts as off.
let falseTokens: Set<string> = set [ "0"; "false"; "no"; "off" ]

[<RequireQualifiedAccess>]
module ConfigKey =

    /// The typed default as text — what the reference doc's Default column
    /// shows and what the seal records for an unset key.
    let defaultText (key: ConfigKey) : string option =
        match key.Kind with
        | ConfigKeyKind.BoolKey(_, d) -> d |> Option.map (fun b -> if b then "true" else "false")
        | ConfigKeyKind.IntKey(_, d) -> d |> Option.map string
        | ConfigKeyKind.EnumKey(_, _, d) -> d
        | ConfigKeyKind.StringKey d -> d

    /// The direction a malformed value fails in, for the kinds that have
    /// one.
    let direction (key: ConfigKey) : Direction option =
        match key.Kind with
        | ConfigKeyKind.BoolKey(direction, _)
        | ConfigKeyKind.EnumKey(_, direction, _) -> Some direction
        | ConfigKeyKind.IntKey _
        | ConfigKeyKind.StringKey _ -> None

    /// A boolean key's value, read by its direction from the raw text the
    /// resolution seam answered (`None` when the key is unset).
    ///
    /// Every reader of a `BoolKey` outside `ServerConfig.fromEnv` goes
    /// through here, so the direction the generated reference documents
    /// is the direction the code has: an on spelling (`trueTokens`) is
    /// `true`, unset is the typed default (`false` when the key declares
    /// none), and anything else is `false` under `Permissive` — a typo
    /// keeps the safe reading — or `Error`, naming the key and the
    /// accepted spellings, under `Protective`. A key of another kind is a
    /// programming error and raises.
    let readBool (key: ConfigKey) (raw: string option) : Result<bool, string> =
        let direction, configured =
            match key.Kind with
            | ConfigKeyKind.BoolKey(direction, defaultValue) -> direction, defaultArg defaultValue false
            | _ -> invalidArg (nameof key) (sprintf "%s is not a boolean key" key.EnvVar)

        match raw |> Option.map _.Trim() |> Option.filter (fun v -> v <> "") with
        | None -> Ok configured
        | Some text ->
            let token = text.ToLowerInvariant()

            if trueTokens.Contains token then
                Ok true
            elif direction = Direction.Permissive || falseTokens.Contains token then
                Ok false
            else
                Error(
                    sprintf
                        "%s=%s is not a recognised boolean value. Expected one of: 1, true, yes, on (case-insensitive) → on; 0, false, no, off → off."
                        key.EnvVar
                        text
                )

    /// `readBool` for a `Permissive` key, whose read never fails.
    let readPermissiveBool (key: ConfigKey) (raw: string option) : bool =
        match readBool key raw with
        | Ok value -> value
        | Error why -> failwith why

    /// The untyped projection.
    let descriptor (key: ConfigKey) : ConfigKeyDescriptor = {
        EnvVar = key.EnvVar
        Description = key.Description
        Type =
            match key.Kind with
            | ConfigKeyKind.BoolKey _ -> BoolKey
            | ConfigKeyKind.IntKey _ -> IntKey
            | ConfigKeyKind.EnumKey(choices, _, _) -> EnumKey choices
            | ConfigKeyKind.StringKey _ -> StringKey
        Default = defaultText key
        IsSecret = key.IsSecret
        Category = key.Category
    }

