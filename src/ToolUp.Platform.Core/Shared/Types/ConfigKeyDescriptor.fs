// ─── What an integer-valued key accepts ─────────────────────────────
//
// `IntKeyRule` is the per-key view of an `IntKey`'s bounds that the
// preflight validator (`IntConfigKeyValidator`), the generated reference and
// the generated JSON Schema read. The bounds themselves are stated once, on
// the key's `ConfigKeyKind.IntKey`; the rows below are derived from them.
//
// **Unlisted keys are not unchecked.** A key that declares nothing beyond
// "an integer" resolves to `unconstrained`, so every `IntKey` inherits the
// format check and only declared bounds add a range.

/// The value contract for one integer-valued config key: the range it
/// accepts, the non-numeric tokens its reader treats as "unset", and
/// the numeric form it parses.
///
/// Bounds are INCLUSIVE, and stated in the key's own unit (bytes for a
/// byte cap) so the refusal can quote the number the operator typed
/// against the number the key accepts.
type IntKeyRule = {
    /// The key this rule governs — the join back to the descriptor.
    EnvVar: string
    /// Inclusive lower bound, when the key declares one.
    Min: int64 option
    /// Inclusive upper bound, when the key declares one.
    Max: int64 option
    /// Raw values accepted verbatim, bypassing both the numeric format
    /// and the range — the reader's own "unset" / "disabled" tokens.
    /// Compared case-insensitively, as the readers compare them.
    AcceptedTokens: string list
    Form: IntKeyNumericForm
}

[<RequireQualifiedAccess>]
module IntKeyRule =

    /// The rule an int key has when it declares nothing: integer format,
    /// no range, no tokens. Every `IntKey` gets at least this.
    let unconstrained (envVar: string) : IntKeyRule = {
        EnvVar = envVar
        Min = None
        Max = None
        AcceptedTokens = []
        Form = IntegerOnly
    }

    /// True when the rule adds nothing to the bare "it is an integer"
    /// contract, so a projection can leave it out rather than render an
    /// empty parenthesis after every int in the table.
    let isUnconstrained (rule: IntKeyRule) : bool =
        rule.Min.IsNone
        && rule.Max.IsNone
        && List.isEmpty rule.AcceptedTokens
        && rule.Form = IntegerOnly

    /// The accepted range and tokens as one operator-facing phrase, or
    /// `None` when there is nothing beyond "an integer" to say.
    ///
    /// One function so the preflight refusal and the generated reference
    /// describe the same contract in the same words — an operator who
    /// reads the table and then reads the refusal must not have to
    /// reconcile two phrasings of one rule.
    let describe (rule: IntKeyRule) : string option =
        let range =
            match rule.Min, rule.Max with
            | Some lo, Some hi -> [ sprintf "%d–%d" lo hi ]
            | Some lo, None -> [ sprintf ">= %d" lo ]
            | None, Some hi -> [ sprintf "<= %d" hi ]
            | None, None -> []

        let form =
            match rule.Form with
            | IntegerOnly -> []
            | IntegerOrDecimal -> [ "fractional values accepted" ]

        let tokens =
            match rule.AcceptedTokens with
            | [] -> []
            | ts -> [ "or " + (ts |> List.map (sprintf "`%s`") |> String.concat " / ") ]

        match range @ form @ tokens with
        | [] -> None
        | parts -> Some(String.concat ", " parts)

/// The value contract an int key's bounds declare, as the per-key rule.
let private intKeyRuleOf (key: ConfigKey) : IntKeyRule option =
    match key.Kind with
    | ConfigKeyKind.IntKey(bounds, _) ->
        Some {
            EnvVar = key.EnvVar
            Min = bounds.Min
            Max = bounds.Max
            AcceptedTokens = bounds.AcceptedTokens
            Form = bounds.Form
        }
    | _ -> None

/// The declared value contracts, one row per int key that needs more than
/// the bare integer format — derived from the keys' bounds. Keys absent
/// from this list are governed by `IntKeyRule.unconstrained`.
let intKeyRules: IntKeyRule list =
    keys
    |> List.choose intKeyRuleOf
    |> List.filter (not << IntKeyRule.isUnconstrained)

/// The value contract for `envVar`. Total: a key with no declared bounds
/// resolves to the unconstrained rule, so a caller never has to decide
/// what an absent row means.
let intKeyRuleFor (envVar: string) : IntKeyRule =
    Map.tryFind envVar keysByName
    |> Option.bind intKeyRuleOf
    |> Option.defaultValue (IntKeyRule.unconstrained envVar)

// ─── Phase 700 — configuration profiles ──────────────────────────────
//
// The operator surface is ~180 keys. Almost none of them are chosen
// independently: a deployment behind a load balancer needs a
// cross-instance notification channel AND a cross-instance lock AND a
// shared rate-limit store, and the existing preflight expresses that
// coupling only NEGATIVELY — a refusal once you have got it wrong, plus
// an acceptance hatch to say you meant it.
//
// A profile is the positive-space twin: a named bundle stating a posture
// once, resolved one rung below the manifest, leaving the operator a
// profile name plus their genuine deltas. It is a CLAIM the preflight
// then checks, not a way around the preflight — see the header of
// `ConfigResolution` for the precedence and the reasoning behind it.
//
// **A profile carries no secrets, and the built-in set is written to
// make that visible rather than to work around it.** The manifest's
// refusal of secret keys applies here for the same reason and with more
// force: a bundle is shared across deployments, so a credential in one
// would be a credential in all of them. `production-multi-instance`
// therefore selects the Redis-backed channel and lock but cannot supply
// `TOOLUP_REDIS_CONNECTION`, and says so in `Requires` — a machine
// -checked field, not a sentence in a doc that can drift from the
// bundle beside it.

/// A named bundle of configuration keys — a posture a deployment can
/// import by name instead of restating key by key.
type ConfigProfile = {
    /// The name a manifest's `"$profile"` entry or `TOOLUP_PROFILE`
    /// selects. Matched case-insensitively, like every enum-valued
    /// reader; this spelling is the canonical one reports use.
    Name: string
    /// What posture this profile claims, in one line. Rendered into the
    /// generated reference, so it is operator-facing prose.
    Description: string
    /// Registered keys the operator must supply THEMSELVES for this
    /// posture to work — secrets and per-deployment values a shareable
    /// bundle structurally cannot carry. Declared rather than described
    /// so it can be checked: every entry must name a registered key.
    Requires: string list
    /// The bundle, in authored order (which is the order the generated
    /// reference renders). Keys are canonical env-var names; values are
    /// strings, so a reader parses a profile value exactly as it parses
    /// an environment one.
    Values: (string * string) list
}

