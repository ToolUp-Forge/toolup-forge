                sb.AppendLine(
                    "These keys are read by the build, the test run or the analyzer, never by a running server. The startup unknown-key preflight guard classifies them as tooling and never reports them, so a development machine that has run a build or a test pack does not warn on its own leftovers."
                )
                |> ignore

                sb.AppendLine "" |> ignore

            sb.AppendLine "| Env var | Type | Default | Secret | Manifest | Description |"
            |> ignore

            sb.AppendLine "|---|---|---|---|---|---|" |> ignore

            let inCategory =
                keys |> List.filter (fun k -> k.Category = category) |> List.sortBy _.EnvVar

            for k in inCategory do
                let defaultCell =
                    match k.Default with
                    | Some d -> cell d
                    | None -> "—"

                let secretCell = if k.IsSecret then "yes" else "no"

                // A secret key can never appear in a manifest (the file's
                // value IS that it is shareable and committable), so the
                // column says "never" rather than "no" — the two are
                // different facts and an operator reading "no" would
                // reasonably wait for a migration that will never come.
                // Phase 698 — a TOOLING key reads `n/a`, not `pending`.
                // `pending` promises a reader that will migrate; for a key
                // the build, the test run or the analyzer reads and no
                // server ever does, no such reader exists and the promise
                // is simply false. The sweep that closed `pending` for the
                // Platform-side keys is what made the distinction visible:
                // what remained was not a queue of unmigrated readers but
                // three different reasons a key cannot be declared.
                let manifestCell =
                    if k.EnvVar = Names.configFile || k.EnvVar = Names.profile then
                        "n/a"
                    elif k.IsSecret then
                        "never"
                    elif isManifestBindable k.EnvVar then
                        "yes"
                    elif isToolingKey k.EnvVar then
                        "n/a"
                    else
                        "pending"

                sb.AppendLine(
                    sprintf
                        "| `%s` | %s | %s | %s | %s | %s |"
                        k.EnvVar
                        (cell (typeLabel k))
                        defaultCell
                        secretCell
                        manifestCell
                        (cell k.Description)
                )
                |> ignore

            sb.AppendLine "" |> ignore

        // Normalise to `\n` so the golden-file comparison is stable
        // across platforms (StringBuilder.AppendLine emits the platform
        // newline; the committed file is `\n`).
        sb.ToString().Replace("\r\n", "\n")

/// Project the registry to `docs/reference/toolup.config.schema.json` —
/// the JSON Schema an editor validates a deployment configuration
/// manifest against while it is being typed. Pure, like `ReferenceDoc`:
/// the same registry always yields the same bytes, so the golden-file
/// test can compare the committed schema against a fresh render.
///
/// **It describes what a valid manifest may contain today, not the whole
/// registry.** A secret key is refused by the loader outright, and a
/// registered key whose reader has not migrated to the resolution seam is
/// accepted-and-warned rather than honoured — so both are omitted, and
/// `additionalProperties: false` reports either at edit time with the same
/// finality the loader has at boot. The property set therefore GROWS as
/// readers migrate; the golden-file test is what keeps the committed copy
/// level with the registry rather than lagging it.
///
/// The `enum` clauses carry each descriptor's declared choices, which are
/// the **canonical** spellings rather than every accepted one: several
/// readers additionally take a hyphenated or abbreviated alias no
/// descriptor lists (`in-memory`, `all-in-one`, `admin`), and all of them
/// match case-insensitively. An editor therefore flags a
/// working-but-undocumented spelling. That is the intended reading — the
/// documented value is the one to write — and the schema's own description
/// says so, because an operator meeting a squiggle on a file that boots
/// needs to be told which of the two is wrong.
[<RequireQualifiedAccess>]
module ConfigSchema =
    open System
    open System.Text

    /// The JSON Schema dialect the generated document declares. 2020-12 is
    /// the current draft and the one editors' bundled validators default
    /// to; it is the schema's own `$schema`, not the manifest's.
    [<Literal>]
    let Dialect = "https://json-schema.org/draft/2020-12/schema"

    /// JSON string escaping. Hand-rolled rather than reached for from a
    /// serialiser because this module sits in the Fable-packed tier and
    /// must build its output from strings alone.
    let private escape (s: string) =
        let sb = StringBuilder()

        for ch in s do
            match ch with
            | '"' -> sb.Append "\\\"" |> ignore
            | '\\' -> sb.Append "\\\\" |> ignore
            | '\n' -> sb.Append "\\n" |> ignore
            | '\r' -> sb.Append "\\r" |> ignore
            | '\t' -> sb.Append "\\t" |> ignore
            | c when c < ' ' -> sb.Append(sprintf "\\u%04x" (int c)) |> ignore
            | c -> sb.Append c |> ignore

        sb.ToString()

    let private str (s: string) = "\"" + escape s + "\""

    /// `true` when `raw` is a JSON-legal integer literal. `Int32.TryParse`
    /// is more permissive than JSON — a leading `+`, leading zeros and
    /// surrounding whitespace all parse for a reader but are not legal
    /// JSON numbers — so a default in any of those shapes is omitted
    /// rather than emitted as a document no validator can load.
    let private isJsonInteger (raw: string) =
        let body = if raw.StartsWith "-" then raw.Substring 1 else raw

        body.Length > 0
        && body |> Seq.forall Char.IsDigit
        && (body = "0" || not (body.StartsWith "0"))

    /// The JSON boolean a descriptor's default text denotes, when it
    /// denotes one. The recognised token set is the readers' own
    /// (`1` / `true` / `yes` / `on` and their negatives).
    let private jsonBool (raw: string) =
        match raw.ToLowerInvariant() with
        | "1"
        | "true"
        | "yes"
        | "on" -> Some "true"
        | "0"
        | "false"
        | "no"
        | "off" -> Some "false"
        | _ -> None

    /// The instance constraint for a key's value.
    ///
    /// Bool and int keys accept **both** the natural JSON scalar and a
    /// string, because that is what the loader accepts: it renders every
    /// scalar back to the string an environment variable would have
    /// carried, so `true` and `"true"` reach the reader identically. The
    /// `pattern` beside an int constrains only the string arm — a
    /// `pattern` keyword ignores every non-string instance — so `3` stays
    /// valid while `"3.5"` and `"soon"` do not.
    /// One literal token as a case-INSENSITIVE ECMA-262 alternative.
    ///
    /// The readers compare their "unset" tokens case-insensitively, and
    /// JSON Schema's `pattern` has no portable inline-flag syntax, so a
    /// letter becomes a two-element class and everything else is escaped
    /// literally. Verbose, and the alternative — emitting only the
    /// lowercase spelling — would flag `NONE` as invalid in the editor
    /// while the reader honours it, which is the defect this projection
    /// exists to stop.
    let private caseInsensitiveLiteral (token: string) =
        token
        |> Seq.map (fun c ->
            if Char.IsLetter c then
                sprintf "[%c%c]" (Char.ToUpperInvariant c) (Char.ToLowerInvariant c)
            elif "\\^$.|?*+()[]{}/".Contains c then
                "\\" + string c
            else
                string c)
        |> String.concat ""

    /// Phase 719 — the instance constraint for an integer-valued key,
    /// read off the SAME `intKeyRules` row the preflight refuses against
    /// and the reference doc's Type column describes.
    ///
    /// Until this phase the projection ignored the rule table and emitted
    /// one clause for every int key: `["integer","string"]` with
    /// `^-?[0-9]+$`. That refused two things the readers honour — the
    /// `none` token three readers take as "leave it unset", and the
    /// fractional value `TOOLUP_STORE_EVICTION_MINUTES` accepts because
    /// its reader is `Double.TryParse` — so an editor validating a
    /// manifest flagged the value the deployment was already running on.
    /// Phase 465 declared both facts; nothing read them here.
    ///
    /// The pattern constrains only the STRING arm (a `pattern` keyword
    /// ignores every non-string instance), which is why `3` stays valid
    /// while `"soon"` does not. It is deliberately the DOCUMENTED
    /// contract rather than a transcription of `TryParse`: the readers
    /// also take a leading `+`, surrounding whitespace and exponent
    /// notation, none of which the reference table offers and none of
    /// which a manifest should be written in — the same line
    /// `isJsonInteger` above already draws for defaults.
    ///
    /// Bounds are NOT emitted. `minimum`/`maximum` would apply to the
    /// numeric arm only, leaving `"512"` valid where `512` was refused —
    /// a schema stricter in one arm than the other says something the
    /// reader does not. Being silent about a bound is looser than the
    /// reader; being wrong about one is the class this phase closes.
    let private intTypeClauses (envVar: string) =
        let rule = intKeyRuleFor envVar

        let numericType, numericPattern =
            match rule.Form with
            | IntegerOnly -> "integer", "-?[0-9]+"
            | IntegerOrDecimal -> "number", "-?[0-9]+(?:\\.[0-9]+)?"

        let alternatives =
            numericPattern :: (rule.AcceptedTokens |> List.map caseInsensitiveLiteral)

        let pattern =
            match alternatives with
            | [ single ] -> "^" + single + "$"
            | many -> "^(?:" + String.concat "|" many + ")$"

        [
            sprintf "\"type\": [ \"%s\", \"string\" ]" numericType
            "\"pattern\": " + str pattern
        ]

    let private typeClauses (k: ConfigKeyDescriptor) =
        match k.Type with
        | StringKey -> [ "\"type\": \"string\"" ]
        | BoolKey -> [ "\"type\": [ \"boolean\", \"string\" ]" ]
        | IntKey -> intTypeClauses k.EnvVar
        | EnumKey choices -> [
            "\"type\": \"string\""
            "\"enum\": [ " + (choices |> List.map str |> String.concat ", ") + " ]"
          ]

    /// The descriptor's default, carried over **only when it is a valid
    /// instance of the property's own schema**.
    ///
    /// `Default` is documentation text, not always a value: a key that is
    /// simply unset until set carries prose (`(unset — probes
    /// ./toolup.config.json)`). In a reference table that reads correctly;
    /// in a schema a `default` is what an editor offers to insert, so a
    /// prose default would be a suggestion that refuses the moment it is
    /// accepted. Anything that does not round-trip — a non-token bool, a
    /// non-JSON integer, a value outside the enum, a parenthesised
    /// annotation — is dropped, and the reference table remains the place
    /// the prose is read.
    let private defaultClauses (k: ConfigKeyDescriptor) =
        match k.Default with
        | None -> []
        | Some raw ->
            let trimmed = raw.Trim()

            match k.Type with
            | BoolKey -> jsonBool trimmed |> Option.map (fun b -> "\"default\": " + b) |> Option.toList
            | IntKey ->
                if isJsonInteger trimmed then
                    [ "\"default\": " + trimmed ]
                else
                    []
            | EnumKey choices ->
                choices
                |> List.tryFind (fun c -> c.ToLowerInvariant() = trimmed.ToLowerInvariant())
                |> Option.map (fun c -> "\"default\": " + str c)
                |> Option.toList
            | StringKey ->
                if trimmed.StartsWith "(" then
                    []
                else
                    [ "\"default\": " + str trimmed ]

    let private block (indent: string) (name: string) (clauses: string list) =
        let inner = indent + "  "
        let body = clauses |> List.map (fun c -> inner + c) |> String.concat ",\n"
        indent + str name + ": {\n" + body + "\n" + indent + "}"

    /// Render the schema for `keys`. Only the manifest-bindable,
    /// non-secret subset appears; properties are ordered by name so the
    /// committed file diffs by the key that changed.
    let render (keys: ConfigKeyDescriptor list) : string =
        let bindable =
            keys
            |> List.filter (fun k -> not k.IsSecret && isManifestBindable k.EnvVar)
            |> List.sortBy _.EnvVar

        let schemaProperty =
            block "    " ManifestSchemaProperty [
                "\"type\": \"string\""
                "\"description\": "
                + str
                    "Optional pointer to this schema, so an editor validates the manifest as it is typed. Tolerated by the loader and never bound to a config key."
            ]

        // Phase 700 — the second tolerated non-registry property.
        // `additionalProperties: false` means an omitted property is an
        // editor error, so the schema has to admit `$profile` or it would
        // flag the very selection the reference doc tells operators to
        // write. Deliberately NOT an `enum` of the built-in names: a
        // consumer may declare its own profiles, and a schema that
        // refused those would be wrong on the file it was generated for.
        let profileProperty =
            block "    " ManifestProfileProperty [
                "\"type\": \"string\""
                "\"description\": "
                + str (
                    sprintf
                        "Name of the configuration profile this manifest imports — a named bundle resolved one rung below the manifest, so every key set here still wins over it. Ships with: %s. A consumer may declare further profiles, so any name is accepted here; an unrecognised one refuses startup and lists what is available."
                        (builtInProfiles |> List.map _.Name |> String.concat ", ")
                )
            ]

        let keyProperties =
            bindable
            |> List.map (fun k ->
                block "    " k.EnvVar ([ "\"description\": " + str k.Description ] @ typeClauses k @ defaultClauses k))

        let properties =
            (schemaProperty :: profileProperty :: keyProperties) |> String.concat ",\n"

        let description =
            sprintf
                "A ToolUp deployment configuration manifest: one JSON file of canonical TOOLUP_* keys, resolved one rung below the environment, optionally importing a named configuration profile via $profile (which resolves one rung below the manifest, so every key set here beats it). It lists the %d keys a manifest may set today — a secret key is refused outright (set the environment variable instead), and a registered key whose reader has not migrated to the config-resolution seam is omitted until it can be honoured. Enum values are every spelling the key's reader accepts, alias spellings included (Phase 719 closed the gap where some were accepted but undeclared); the readers also compare case-insensitively, so a value flagged here for its LETTER CASE alone still boots — write it as listed. Full descriptions, defaults and per-key manifest status: docs/reference/config-reference.md."
                bindable.Length

        let sb = StringBuilder()

        sb.Append("{\n") |> ignore
        sb.Append("  \"$schema\": " + str Dialect + ",\n") |> ignore

        sb.Append(
            "  \"$comment\": "
            + str
                "GENERATED FILE — do not edit by hand. Regenerate with dev-scripts/generate-config-reference.ps1. The source of truth is ConfigKeys.all in src/ToolUp.Platform.Core/Shared/Types/ConfigKeyDescriptor.fs."
            + ",\n"
        )
        |> ignore

        sb.Append("  \"title\": " + str "ToolUp deployment configuration manifest" + ",\n")
        |> ignore

        sb.Append("  \"description\": " + str description + ",\n") |> ignore
        sb.Append("  \"type\": \"object\",\n") |> ignore
        sb.Append("  \"additionalProperties\": false,\n") |> ignore
        sb.Append("  \"properties\": {\n") |> ignore
        sb.Append(properties) |> ignore
        sb.Append("\n  }\n") |> ignore
        sb.Append("}\n") |> ignore

        // `\n` throughout by construction (no `AppendLine`), so the
        // committed bytes are identical on every platform.
        sb.ToString()

/// Phase 765 — the registry's third projection, and the only one that is
/// a COLUMN rather than a whole file.
///
/// `docs/operations/env-vars.md` is the operator-facing page, and it is
/// not a candidate for whole-file generation: it covers a curated subset
/// of the registry's keys, and each row carries two facts the registry
/// does not hold — the `ServerConfig` field the value binds to, and the
/// reader's parse contract (`Positive integer 1–65535; out-of-range →
/// fail loud`). Generating the page outright would delete both; leaving
/// it entirely hand-authored is what let Phase 9m.C move
/// `TOOLUP_TRACE_CATEGORIES`'s description in the registry while the
/// operations table went on describing it in one stale sentence.
///
/// So the projection is per-CELL. A table opts in by heading its first
/// column `Variable` and carrying a column headed `Description`; every
/// row in it whose variable is a registered key has that one cell
/// rewritten from the descriptor, and every other byte of the file —
/// prose, the other columns, the tables that did not opt in — is passed
/// through unchanged. `render` is therefore idempotent and total: the
/// golden-file arm asserts `committed = render all committed`, so a
/// descriptor edit that was not regenerated is a red gate rather than a
/// stale page.
///
/// `issues` is the half a byte-comparison structurally cannot do. The
/// compare quantifies over what the page HAS, so a table that dropped
/// its `Description` column, or a row naming a key that was renamed out
/// of the registry, would both pass it silently — the projection would
/// simply have nothing to say about either. Each is reported by name.
[<RequireQualifiedAccess>]
module OperationsDoc =
    open System
    open System.Text

    /// The page this module projects into, repo-relative. Named here
    /// rather than at the test that reads it: the generator script, the
    /// gate and the conventions note all cite one path.
    [<Literal>]
    let DocPath = "docs/operations/env-vars.md"

    /// A table opts in by naming its first column this.
    [<Literal>]
    let VariableHeader = "Variable"

    /// …and by carrying a column headed this. Position-independent: the
    /// column reads best beside the variable in some tables and after
    /// the parse contract in others, and the projection should not be
    /// what decides that.
    [<Literal>]
    let DescriptionHeader = "Description"

    /// Markdown-escape a cell value — the same escape `ReferenceDoc`
    /// applies, and for the same reason: an unescaped `|` in a
    /// description would silently split the row into two columns.
    let private escape (s: string) = s.Replace("|", "\\|")

    /// Split a markdown table row into its cells, honouring the `\|`
    /// escape above. A naive `Split('|')` would tear a description
    /// containing an escaped pipe into two cells and then write it back
    /// as a malformed row.
    let private splitCells (row: string) =
        let t = row.Trim()
        let acc = ResizeArray<string>()
        let sb = StringBuilder()
        let mutable i = 0

        while i < t.Length do
            if t[i] = '\\' && i + 1 < t.Length && t[i + 1] = '|' then
                sb.Append "\\|" |> ignore
                i <- i + 2
            elif t[i] = '|' then
                acc.Add(sb.ToString().Trim())
                sb.Clear() |> ignore
                i <- i + 1
            else
                sb.Append t[i] |> ignore
                i <- i + 1

        acc.Add(sb.ToString().Trim())

        // The outer pipes contribute one empty segment at each end.
        match List.ofSeq acc with
        | [] -> []
        | _ :: rest -> rest |> List.truncate (max 0 (List.length rest - 1))

    let private isTableRow (line: string) = line.TrimStart(' ').StartsWith "|"

    /// `|---|---|` and its aligned variants.
    let private isSeparatorRow (line: string) =
        let cells = splitCells line

        not cells.IsEmpty
        && cells
           |> List.forall (fun c ->
               c.Length > 0
               && c |> Seq.forall (fun ch -> ch = '-' || ch = ':' || ch = ' ')
               && c |> Seq.exists (fun ch -> ch = '-'))

    /// The variable a row names, when its first cell is a backticked
    /// `TOOLUP_*` token. Anything else — `SERVER_PORT`, a `__TOOLUP_*__`
    /// Vite define, a prose cell — is not a registry key and is left
    /// alone.
    let private registryVariableOf (cells: string list) =
        match cells with
        | first :: _ when first.Length > 2 && first.StartsWith "`" && first.EndsWith "`" ->
            let name = first.Substring(1, first.Length - 2)
            if name.StartsWith "TOOLUP_" then Some name else None
        | _ -> None

    let private rebuild (cells: string list) = "| " + String.concat " | " cells + " |"

    /// One opted-in table found in the page: where it starts, how wide
    /// it is, and which column carries the description.
    type private OptedInTable = {
        HeaderLine: int
        CellCount: int
        DescriptionIndex: int option
    }

    /// Walk the page once, returning every opted-in table and a map from
    /// each body-row line index to the table it belongs to.
    let private scan (lines: string[]) =
        let tables = ResizeArray<OptedInTable>()
        let bodyOf = System.Collections.Generic.Dictionary<int, OptedInTable>()
        let mutable i = 0

        while i < lines.Length do
            let startsTable =
                isTableRow lines[i]
                && not (isSeparatorRow lines[i])
                && i + 1 < lines.Length
                && isSeparatorRow lines[i + 1]

            if startsTable then
                let header = splitCells lines[i]

                match header with
                | first :: _ when first = VariableHeader ->
                    let table = {
                        HeaderLine = i
                        CellCount = List.length header
                        DescriptionIndex = header |> List.tryFindIndex (fun c -> c = DescriptionHeader)
                    }

                    tables.Add table
                    let mutable j = i + 2

                    while j < lines.Length && isTableRow lines[j] do
                        bodyOf[j] <- table
                        j <- j + 1

                    i <- j
                | _ -> i <- i + 1
            else
                i <- i + 1

        List.ofSeq tables, bodyOf

    /// Rewrite the description cell of every registry-backed row in an
    /// opted-in table; pass every other byte through.
    ///
    /// Total by construction: a row whose cell count does not match its
    /// header, a variable with no descriptor, and a table with no
    /// `Description` column are all passed through unchanged here and
    /// reported by `issues` instead. A projection that threw would make
    /// the gate's failure mode a crash rather than a diff, and a crash
    /// says nothing about which row is wrong.
    let render (keys: ConfigKeyDescriptor list) (committed: string) : string =
        let byVar = keys |> List.map (fun k -> k.EnvVar, k) |> Map.ofList
        let lines = committed.Replace("\r\n", "\n").Split '\n'
        let _, bodyOf = scan lines

        let projected =
            lines
            |> Array.mapi (fun idx line ->
                match bodyOf.TryGetValue idx with
                | true, table ->
                    match table.DescriptionIndex with
                    | None -> line
                    | Some di ->
                        let cells = splitCells line

                        if List.length cells <> table.CellCount then
                            line
                        else
                            match registryVariableOf cells |> Option.bind (fun n -> Map.tryFind n byVar) with
                            | None -> line
                            | Some descriptor ->
                                cells
                                |> List.mapi (fun ci c -> if ci = di then escape descriptor.Description else c)
                                |> rebuild
                | _ -> line)

        String.Join("\n", projected)

    /// Findings the byte-comparison cannot make: an opted-in table that
    /// carries no description column, a row whose cell count disagrees
    /// with its header (so the projection would silently skip it), and a
    /// `TOOLUP_*` variable the registry does not describe.
    let issues (keys: ConfigKeyDescriptor list) (committed: string) : string list =
        let registered = keys |> List.map _.EnvVar |> Set.ofList
        let lines = committed.Replace("\r\n", "\n").Split '\n'
        let tables, bodyOf = scan lines

        let missingColumn =
            tables
            |> List.filter (fun t -> t.DescriptionIndex.IsNone)
            |> List.map (fun t ->
                sprintf
                    "line %d: a table headed `%s` carries no `%s` column, so the registry's description for its keys is projected nowhere on this page"
                    (t.HeaderLine + 1)
                    VariableHeader
                    DescriptionHeader)

        let rowFindings =
            bodyOf
            |> Seq.sortBy _.Key
            |> Seq.collect (fun kv ->
                let cells = splitCells lines[kv.Key]

                if List.length cells <> kv.Value.CellCount then
                    [
                        sprintf
                            "line %d: row has %d cells but its header declares %d, so no column can be projected into it"
                            (kv.Key + 1)
                            (List.length cells)
                            kv.Value.CellCount
                    ]
                else
                    match registryVariableOf cells with
                    | Some name when not (Set.contains name registered) -> [
                        sprintf
                            "line %d: names `%s`, which has no ConfigKeyDescriptor — it was renamed or removed from the registry, and this row now documents a variable nothing reads"
                            (kv.Key + 1)
                            name
                      ]
                    | _ -> [])
            |> List.ofSeq

        missingColumn @ rowFindings

/// The boot seal's view of the configuration: one rendering per key whose
/// `Seal` posture admits it, computed from the key's resolved value.
///
/// The seal records what the deployment STATES, read through the same
/// resolution seam the readers use, so a value set by the environment, the
/// manifest or the profile seals alike. An unset key seals as its typed
/// default, so writing the default out explicitly is not drift; one with no
/// typed default seals as `(unset)`.
[<RequireQualifiedAccess>]
module ConfigKeySeal =

    /// What an unset key with no typed default seals as.
    [<Literal>]
    let Unset = "(unset)"

    /// The rendering `key` seals as when its resolved value is `raw`, or
    /// `None` when the key is not sealed. A boolean seals as `true` /
    /// `false` whichever accepted spelling set it, and a token seals in
    /// lower case, so a spelling change of the same value is not drift.
    let render (key: ConfigKey) (raw: string option) : string option =
        let value = raw |> Option.map _.Trim() |> Option.filter (fun v -> v <> "")

        match key.Seal with
        | SealPosture.Unsealed _ -> None
        | SealPosture.SealPresence -> Some(if value.IsSome then "set" else "unset")
        | SealPosture.SealValue ->
            match value with
            | None -> Some(ConfigKey.defaultText key |> Option.defaultValue Unset)
            | Some v ->
                match key.Kind with
                | ConfigKeyKind.BoolKey _ ->
                    let lower = v.ToLowerInvariant()

                    if trueTokens.Contains lower then Some "true"
                    elif falseTokens.Contains lower then Some "false"
                    else Some v
                | ConfigKeyKind.EnumKey _ -> Some(v.ToLowerInvariant())
                | ConfigKeyKind.IntKey _
                | ConfigKeyKind.StringKey _ -> Some v

    /// The sealed rendering of every sealable key in `keys`, by name, sorted.
    let project (read: string -> string option) (keys: ConfigKey list) : (string * string) list =
        keys
        |> List.choose (fun k -> render k (read k.EnvVar) |> Option.map (fun r -> k.EnvVar, r))
        |> List.sortBy fst

/// The generated region of `DEPLOYMENT.md`: which keys refuse a typo, and
/// which the boot seal covers. Projected from `keys`, so the tables cannot
/// disagree with the readers that resolve through the registry.
[<RequireQualifiedAccess>]
module DeploymentDoc =

    /// The repo-relative page the region lives in.
    [<Literal>]
    let DocPath = "DEPLOYMENT.md"

    /// The line that opens the generated region.
    [<Literal>]
    let BeginMarker =
        "<!-- BEGIN GENERATED: config-key directions and seal coverage. Regenerate with `dotnet run --project Build.fsproj -- GenerateConfigReference`; do not edit by hand. -->"

    /// The line that closes it.
    [<Literal>]
    let EndMarker = "<!-- END GENERATED: config-key directions and seal coverage -->"

    let private cell (s: string) = s.Replace("|", "\\|")

    let private directionCell =
        function
        | Direction.Protective -> "protective — **stops startup**"
        | Direction.Permissive -> "permissive — keeps the default"

    let private defaultCell (key: ConfigKey) =
        match ConfigKey.defaultText key with
        | Some d -> sprintf "`%s`" (cell d)
        | None -> "—"

    /// The region's body, between the markers.
    let render (keys: ConfigKey list) : string =
        let served = keys |> List.filter (fun k -> k.Category <> ToolingCategory)

        let booleans =
            served
            |> List.choose (fun k ->
                match k.Kind with
                | ConfigKeyKind.BoolKey(direction, _) -> Some(k, direction)
                | _ -> None)
            |> List.sortBy (fun (k, _) -> k.EnvVar)

        let unions =
            served
            |> List.choose (fun k ->
                match k.Kind with
                | ConfigKeyKind.EnumKey(choices, direction, _) -> Some(k, direction, choices)
                | _ -> None)
            |> List.sortBy (fun (k, _, _) -> k.EnvVar)

        let presence =
            keys
            |> List.filter (fun k -> k.Seal = SealPosture.SealPresence)
            |> List.map _.EnvVar
            |> List.sort

        let unsealed =
            served
            |> List.choose (fun k ->
                match k.Seal with
                | SealPosture.Unsealed reason -> Some(k.EnvVar, reason)
                | _ -> None)
            |> List.sortBy fst

        let tooling = keys |> List.filter (fun k -> k.Category = ToolingCategory)

        let sealedByValue =
            keys |> List.filter (fun k -> k.Seal = SealPosture.SealValue) |> List.length

        [
            yield BeginMarker
            yield ""
            yield "### Boolean keys"
            yield ""
            yield "| Key | A malformed value | Default |"
            yield "|---|---|---|"
            for k, direction in booleans do
                let effect =
                    match direction with
                    | Direction.Protective -> "**stops startup** (protective)"
                    | Direction.Permissive -> "reads as `false` (permissive)"

                yield sprintf "| `%s` | %s | %s |" k.EnvVar effect (defaultCell k)
            yield ""
            yield "### Union keys"
            yield ""
            yield "| Key | Direction | Accepted tokens | Default |"
            yield "|---|---|---|---|"
            for k, direction, choices in unions do
                yield
                    sprintf
                        "| `%s` | %s | %s | %s |"
                        k.EnvVar
                        (directionCell direction)
                        (choices |> List.map cell |> String.concat ", ")
                        (defaultCell k)
            yield ""
            yield "### Boot seal coverage"
            yield ""
            yield
                sprintf
                    "%d keys are sealed by value. %d secrets are sealed by presence only (set or unset), so the credential is never written into the seal: %s."
                    sealedByValue
                    presence.Length
                    (presence |> List.map (sprintf "`%s`") |> String.concat ", ")
            yield ""
            yield
                sprintf
                    "The %d keys in the reference's %s section are not sealed: they are read by build, test and analyzer tooling, never by a running server. Nor are these, so changing one is not drift:"
                    tooling.Length
                    ToolingCategory
            yield ""
            yield "| Key | Why it is not sealed |"
            yield "|---|---|"
            for name, reason in unsealed do
                yield sprintf "| `%s` | %s |" name (cell reason)
            yield ""
            yield EndMarker
        ]
        |> String.concat "\n"

    /// `committed` with its generated region replaced by `render keys`, or
    /// an error naming what is wrong with the markers.
    let splice (keys: ConfigKey list) (committed: string) : Result<string, string> =
        let text = committed.Replace("\r\n", "\n")
        let start = text.IndexOf BeginMarker
        let stop = text.IndexOf EndMarker

        if start < 0 || stop < 0 then
            Error(sprintf "%s carries no generated region: both marker lines must be present." DocPath)
        elif stop < start then
            Error(sprintf "%s: the end marker precedes the begin marker." DocPath)
        elif text.IndexOf(BeginMarker, start + 1) >= 0 then
            Error(sprintf "%s carries the begin marker twice." DocPath)
        else
            Ok(text.Substring(0, start) + render keys + text.Substring(stop + EndMarker.Length))